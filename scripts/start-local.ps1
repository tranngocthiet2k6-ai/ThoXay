param(
    [switch]$SkipBuild,
    [switch]$WithFrontend,
    [switch]$Background,
    [switch]$OpenBrowser
)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent

function Test-LocalPort([int]$Port) {
    $client = New-Object System.Net.Sockets.TcpClient
    try {
        $connection = $client.ConnectAsync('127.0.0.1', $Port)
        return ($connection.Wait(500) -and $client.Connected)
    } catch { return $false } finally { $client.Dispose() }
}

function Wait-LocalPage([string]$Url, [System.Diagnostics.Process]$Process) {
    for ($attempt = 0; $attempt -lt 60; $attempt++) {
        $Process.Refresh()
        if ($Process.HasExited) { throw "Process exited before $Url was ready. Check .local logs." }
        try {
            $request = [System.Net.WebRequest]::Create($Url)
            $request.Proxy = $null
            $request.Timeout = 2000
            $response = $request.GetResponse()
            try { if ([int]$response.StatusCode -eq 200) { return } } finally { $response.Dispose() }
        } catch { }
        Start-Sleep -Milliseconds 500
    }
    throw "Timed out waiting for $Url. Check .local logs."
}

Push-Location $projectRoot
try {
    $localDirectory = Join-Path $projectRoot '.local'
    New-Item -ItemType Directory -Path $localDirectory -Force | Out-Null
    $localConfiguration = Join-Path $localDirectory 'application.properties'
    $databaseUrl = 'jdbc:postgresql://localhost:5432/tho_xay_db'
    $portableWasConfigured = (Test-Path -LiteralPath $localConfiguration) -and
        [System.IO.File]::ReadAllText($localConfiguration).Contains('jdbc:postgresql://127.0.0.1:55432/tho_xay_db')

    if (-not $env:DB_URL -and ($portableWasConfigured -or -not (Test-LocalPort 5432))) {
        $pgBin = Join-Path $projectRoot '.tools\postgres\pgsql\bin'
        $pgData = Join-Path $projectRoot '.tools\pgdata'
        if (-not (Test-Path (Join-Path $pgBin 'pg_ctl.exe')) -or -not (Test-Path (Join-Path $pgData 'PG_VERSION'))) {
            throw 'PostgreSQL is not listening on localhost:5432. Start PostgreSQL/Docker or set DB_URL, DB_USERNAME and DB_PASSWORD.'
        }
        & (Join-Path $pgBin 'pg_ctl.exe') -D $pgData status *> (Join-Path $localDirectory 'postgres-status.log')
        if ($LASTEXITCODE -ne 0) {
            if (Test-LocalPort 55432) { throw 'Port 55432 is occupied by another process; the project PostgreSQL was not started.' }
            & (Join-Path $pgBin 'pg_ctl.exe') -D $pgData -l (Join-Path $localDirectory 'postgres.log') -o '-h 127.0.0.1 -p 55432' start
            if ($LASTEXITCODE -ne 0) { throw 'Cannot start the project PostgreSQL. Check .local/postgres.log.' }
        }
        & (Join-Path $pgBin 'pg_isready.exe') -h 127.0.0.1 -p 55432 -q
        if ($LASTEXITCODE -ne 0) { throw 'Project PostgreSQL is not ready on localhost:55432.' }
        $databaseUrl = 'jdbc:postgresql://127.0.0.1:55432/tho_xay_db'
        $exists = & (Join-Path $pgBin 'psql.exe') -h 127.0.0.1 -p 55432 -U postgres -d postgres -At -v ON_ERROR_STOP=1 -c "SELECT 1 FROM pg_database WHERE datname='tho_xay_db';"
        if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect the project PostgreSQL database.' }
        if ($exists -ne '1') {
            & (Join-Path $pgBin 'createdb.exe') -h 127.0.0.1 -p 55432 -U postgres tho_xay_db
            if ($LASTEXITCODE -ne 0) { throw 'Cannot create tho_xay_db.' }
        }
        $tables = & (Join-Path $pgBin 'psql.exe') -h 127.0.0.1 -p 55432 -U postgres -d tho_xay_db -At -v ON_ERROR_STOP=1 -c "SELECT count(*) FROM information_schema.tables WHERE table_schema='public' AND table_name IN ('users','jobs','job_applications');"
        if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect the project schema.' }
        if ($tables -ne '3') {
            & (Join-Path $pgBin 'psql.exe') -h 127.0.0.1 -p 55432 -U postgres -d tho_xay_db -v ON_ERROR_STOP=1 -f (Join-Path $projectRoot 'schema.sql')
            if ($LASTEXITCODE -ne 0) { throw 'Cannot initialize schema.sql.' }
        }
        & (Join-Path $pgBin 'psql.exe') -h 127.0.0.1 -p 55432 -U postgres -d tho_xay_db -v ON_ERROR_STOP=1 -c 'SET client_min_messages=WARNING' -f (Join-Path $projectRoot 'migrations\002_worker_ratings.sql')
        if ($LASTEXITCODE -ne 0) { throw 'Cannot apply the worker ratings migration.' }
        & (Join-Path $pgBin 'psql.exe') -h 127.0.0.1 -p 55432 -U postgres -d tho_xay_db -v ON_ERROR_STOP=1 -c 'SET client_min_messages=WARNING' -f (Join-Path $projectRoot 'migrations\003_cccd_front_back.sql')
        if ($LASTEXITCODE -ne 0) { throw 'Cannot apply the front/back CCCD migration.' }
    }

    if (-not (Test-Path -LiteralPath $localConfiguration)) {
        $jwtBytes = New-Object byte[] 48
        $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
        try { $random.GetBytes($jwtBytes) } finally { $random.Dispose() }
        $localJwtKey = [Convert]::ToBase64String($jwtBytes)
        $configuration = @(
            '# Local settings generated by scripts/start-local.ps1; ignored by Git.',
            ('spring.datasource.url=${DB_URL:' + $databaseUrl + '}'),
            'spring.datasource.username=${DB_USERNAME:postgres}',
            'spring.datasource.password=${DB_PASSWORD:postgres}',
            ('app.jwt.secret=${JWT_SECRET:' + $localJwtKey + '}')
        ) -join [Environment]::NewLine
        [System.IO.File]::WriteAllText($localConfiguration, $configuration, (New-Object System.Text.UTF8Encoding($false)))
        Write-Host 'Created private local configuration and a persistent JWT key in .local/.'
    }

    $backendPort = if ($env:PORT) { [int]$env:PORT } else { 8080 }
    if (Test-LocalPort $backendPort) { throw "Port $backendPort is already occupied. Stop the existing server or set PORT to a free port." }
    if ($WithFrontend -and (Test-LocalPort 3000)) { throw 'Port 3000 is already occupied. Stop the existing frontend first.' }
    if (-not $SkipBuild) {
        & .\mvnw.cmd -B verify
        if ($LASTEXITCODE -ne 0) { throw 'Maven verify failed.' }
    }
    $jarPath = Join-Path $projectRoot 'target\tho-xay-1.0.0.jar'
    if (-not (Test-Path -LiteralPath $jarPath)) { throw 'Build the application before using -SkipBuild.' }
    $webProcess = $null
    if ($WithFrontend) {
        $flutterPath = Join-Path $projectRoot '.tools\flutter\bin\flutter.bat'
        if (-not (Test-Path $flutterPath)) { $flutterPath = (Get-Command flutter -ErrorAction Stop).Source }
        if (-not $SkipBuild -or $backendPort -ne 8080) {
            Push-Location (Join-Path $projectRoot 'mobile_app')
            try {
                & $flutterPath pub get
                if ($LASTEXITCODE -ne 0) { throw 'Flutter pub get failed.' }
                & $flutterPath build web --release --no-wasm-dry-run "--dart-define=API_BASE_URL=http://localhost:$backendPort"
                if ($LASTEXITCODE -ne 0) { throw 'Flutter build web failed.' }
            } finally { Pop-Location }
        }
        $webRoot = Join-Path $projectRoot 'mobile_app\build\web'
        if (-not (Test-Path (Join-Path $webRoot 'index.html'))) { throw 'Build Flutter Web before using -SkipBuild.' }
        $nodePath = (Get-Command node -ErrorAction Stop).Source
        $webScript = Join-Path $PSScriptRoot 'serve-web.cjs'
    }

    if ($Background -or $WithFrontend) {
        $javaPath = (Get-Command java -ErrorAction Stop).Source
        $backendProcess = Start-Process -FilePath $javaPath -ArgumentList @('-jar', ('"' + $jarPath + '"')) -WorkingDirectory $projectRoot -WindowStyle Hidden -RedirectStandardOutput (Join-Path $localDirectory 'backend.log') -RedirectStandardError (Join-Path $localDirectory 'backend-error.log') -PassThru
        $stateFile = Join-Path $localDirectory 'processes.json'
        @{ backend = $backendProcess.Id; frontend = $null } | ConvertTo-Json | Set-Content $stateFile
        try {
            Wait-LocalPage "http://127.0.0.1:$backendPort/admin/login" $backendProcess
            if ($WithFrontend) {
                $webProcess = Start-Process -FilePath $nodePath -ArgumentList @(('"' + $webScript + '"'), ('"' + $webRoot + '"'), '3000') -WorkingDirectory $projectRoot -WindowStyle Hidden -RedirectStandardOutput (Join-Path $localDirectory 'frontend.log') -RedirectStandardError (Join-Path $localDirectory 'frontend-error.log') -PassThru
                @{ backend = $backendProcess.Id; frontend = $webProcess.Id } | ConvertTo-Json | Set-Content $stateFile
                Wait-LocalPage 'http://127.0.0.1:3000' $webProcess
            }
        } catch {
            $backendProcess.Refresh()
            if (-not $backendProcess.HasExited) { $backendProcess.Kill() }
            if ($webProcess) { $webProcess.Refresh(); if (-not $webProcess.HasExited) { $webProcess.Kill() } }
            throw
        }
        Write-Host "Backend / Admin: http://localhost:$backendPort/admin/login"
        if ($WithFrontend) { Write-Host 'Flutter Web: http://localhost:3000' }
        Write-Host 'Logs: .local/. Stop the application with scripts/stop-local.ps1.'
        if ($OpenBrowser) {
            Start-Process "http://localhost:$backendPort/admin/login"
            if ($WithFrontend) { Start-Process 'http://localhost:3000' }
        }
    } else {
        & java -jar $jarPath
        if ($LASTEXITCODE -ne 0) { throw 'The application stopped with an error.' }
    }
} finally {
    Pop-Location
}
